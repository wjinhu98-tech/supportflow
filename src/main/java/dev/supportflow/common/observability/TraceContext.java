package dev.supportflow.common.observability;

import org.slf4j.MDC;

import java.util.UUID;
import java.util.regex.Pattern;

/** Caller-thread correlation only. No implicit inheritance into executors or provider HTTP worker threads. */
public final class TraceContext implements AutoCloseable {
    private static final Pattern TRACE = Pattern.compile("[0-9a-f]{32}");
    private static final Pattern RUN = Pattern.compile("[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}");
    private final String previousTrace;
    private final String previousRun;

    private TraceContext(String trace, String run) {
        previousTrace = MDC.get("traceId");
        previousRun = MDC.get("agentRunId");
        put("traceId", trace);
        put("agentRunId", run);
    }

    /** Always generated by the server. An inbound X-Trace-Id is deliberately not trusted or reflected. */
    public static TraceContext beginRequest() { return new TraceContext(UUID.randomUUID().toString().replace("-", ""), null); }

    /** The UUID comes from the persisted, ownership-validated AgentRun, not a raw HTTP parameter. */
    public static TraceContext agentRun(UUID runId) { return new TraceContext(traceIdOrNull(), runId.toString()); }

    public static String traceId() { String value = traceIdOrNull(); return value == null ? "none" : value; }

    public static String agentRunId() {
        String value = MDC.get("agentRunId");
        return value != null && RUN.matcher(value).matches() ? value : "none";
    }

    private static String traceIdOrNull() {
        String value = MDC.get("traceId");
        return value != null && TRACE.matcher(value).matches() ? value : null;
    }

    @Override public void close() {
        put("traceId", previousTrace);
        put("agentRunId", previousRun);
    }

    private static void put(String key, String value) { if (value == null) MDC.remove(key); else MDC.put(key, value); }
}
